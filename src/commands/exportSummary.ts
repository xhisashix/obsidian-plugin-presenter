export interface SlideLayoutBlueprint {
	archetype: string;
	layoutIntent: string;
}

/**
 * Infers the consulting slide archetype and layout intent from a parsed SlideData.
 */
export function inferSlideLayoutBlueprint(slide: SlideData): SlideLayoutBlueprint {
	const type = slide.layout ?? slide.type;
	if (type === 'cover') {
		return {
			archetype: 'Cover Slide',
			layoutIntent: 'Centered presentation title, subtitle, and speaker/date metadata.',
		};
	}
	if (type === 'section') {
		return {
			archetype: 'Section Divider',
			layoutIntent: 'Centered section headline card separating major story chapters.',
		};
	}
	if (type === 'quote') {
		return {
			archetype: 'Quote / Big Statement',
			layoutIntent: 'Centered high-impact statement or executive quote.',
		};
	}

	const md = slide.markdown;

	if (md.includes('presenter-cols-pyramid')) {
		return {
			archetype: 'Pyramid Hierarchy (ピラミッド階層図型)',
			layoutIntent: '3-tier pyramid diagram on the left (Top / Middle / Base) paired with detailed tier descriptions on the right.',
		};
	}
	if (md.includes('presenter-cols-funnel')) {
		return {
			archetype: 'Funnel & Conversion (ファネル・転換率分析型)',
			layoutIntent: 'Progressive conversion funnel stages on the left with stage metrics and bottleneck analysis on the right.',
		};
	}
	if (md.includes('presenter-cols-matrix')) {
		return {
			archetype: '2x2 Positioning Matrix (2軸4象限マトリクス型)',
			layoutIntent: '2x2 four-quadrant grid evaluating options across two axes, highlighting the top-right priority quadrant.',
		};
	}
	if (md.includes('presenter-cols-cycle')) {
		return {
			archetype: 'Continuous Cycle Loop (サイクル・循環型)',
			layoutIntent: '4-step continuous flywheel loop arranged clockwise around a core value engine.',
		};
	}
	if (md.includes('presenter-chart-bars')) {
		return {
			archetype: 'Chart & Insight (チャート＋インサイト抽出型)',
			layoutIntent: 'Split 2:1 layout with quantitative bar chart evidence on the left and strategic insight/takeaway on the right.',
		};
	}
	if (md.includes('presenter-kpi-value')) {
		return {
			archetype: 'Big Number KPI (ビッグナンバー単一指標型)',
			layoutIntent: 'Dominant single KPI metric centered on the slide supported by a concise impact summary callout.',
		};
	}
	if (md.includes('presenter-cols-step')) {
		return {
			archetype: 'Horizontal Step Flow (ホリゾンタルフロー型)',
			layoutIntent: 'Left-to-right sequential step cards (STEP 01 -> STEP 02 -> STEP 03) showing phase progression.',
		};
	}
	if (md.includes('presenter-cols-ratio-2-1') && md.includes('presenter-cols-3')) {
		return {
			archetype: 'Bento Box Dashboard (弁当箱型ダッシュボード)',
			layoutIntent: 'Modular multi-row dashboard combining a 2:1 top hero row with a 3-column metric grid below.',
		};
	}
	if (md.includes('presenter-cols-3') && /^>\s*\[!(important|tip|summary|warning)\]/im.test(md)) {
		if (/\[!tip\]/i.test(md)) {
			return {
				archetype: 'Vertical Tower Flow (縦並び＋右向きフロー型)',
				layoutIntent: 'Top end-to-end flow banner above 3 vertical phase columns listing tasks, deliverables, and exit criteria.',
			};
		}
		return {
			archetype: 'Executive Summary (結論＋3カラム SCQA型)',
			layoutIntent: 'Top full-width conclusion callout banner supported by 3 equal columns below (Situation / Findings / Recommendation).',
		};
	}
	if (md.includes('presenter-cols-3')) {
		return {
			archetype: '3-Column Pillars (3カラム・ピラー型)',
			layoutIntent: '3 equal-width vertical pillar cards comparing parallel strategic pillars or options.',
		};
	}
	if (md.includes('presenter-cols-ratio-1-2') || md.includes('presenter-cols-ratio-2-1') || md.includes('presenter-cols-2')) {
		return {
			archetype: '2-Column Comparison (2カラム比較・対比型)',
			layoutIntent: 'Side-by-side 2-column layout pairing key arguments on the left with visual evidence or Before/After comparison on the right.',
		};
	}
	if (/^\|.+\|\s*$/m.test(md)) {
		return {
			archetype: 'Swimlane / Structured Matrix Table (スイムレーン・構造化テーブル型)',
			layoutIntent: 'Structured matrix table mapping roles/dimensions across columns, paired with a key takeaway callout.',
		};
	}

	return {
		archetype: 'Standard Content Slide',
		layoutIntent: ' Focused 1-slide-1-message layout with action title and structured key points.',
	};
}

/**
 * Cleans internal HTML wrapper tags generated by preprocessing so that the blueprint body
 * stays clean, readable Markdown for AI slide generators and LLMs.
 */
export function cleanSlideMarkdownForBlueprint(markdown: string): string {
	let cleaned = markdown;

	// Remove heading line if it duplicates the slide's Action Title (H1/H2 at the top)
	cleaned = cleaned.replace(/^\s*#{1,2}\s+[^\r\n]+\r?\n*/, '');

	// Replace column wrapper divs with readable section separators
	cleaned = cleaned.replace(/<div class="presenter-cols[^"]*">/g, '');
	cleaned = cleaned.replace(/<div class="presenter-col[^"]*">/g, '');
	cleaned = cleaned.replace(/<div class="presenter-tier-shape">/g, '');
	cleaned = cleaned.replace(/<div class="presenter-tier-detail">/g, '');
	cleaned = cleaned.replace(/<div class="presenter-chart-bars">/g, '');
	cleaned = cleaned.replace(
		/<div class="presenter-chart-row[^"]*">\s*<div class="presenter-chart-label">(.*?)<\/div>\s*<div class="presenter-chart-track"><div class="presenter-chart-fill" style="width:\s*([0-9.]+)%"><\/div><\/div>\s*<div class="presenter-chart-meta">(.*?)<\/div>\s*<\/div>/g,
		'- $1 | $3 ($2%)'
	);
	cleaned = cleaned.replace(/<div class="presenter-kpi-value">(.*?)<\/div>/g, '**KPI: $1**');
	cleaned = cleaned.replace(
		/<span class="presenter-card-eyebrow">(.*?)<\/span>\s*<span class="presenter-card-title">(.*?)<\/span>/g,
		'$1. $2'
	);
	cleaned = cleaned.replace(/<span class="presenter-card-(?:eyebrow|title)">(.*?)<\/span>/g, '$1');
	cleaned = cleaned.replace(/<span class="presenter-badge">(.*?)<\/span>/g, '[$1]');
	cleaned = cleaned.replace(/<\/div>/g, '');

	// Clean up excessive blank lines
	cleaned = cleaned.replace(/\n{3,}/g, '\n\n').trim();
	return cleaned;
}

/**
 * Cleans speaker notes (`> [!note] ...`) into plain readable script text.
 */
export function cleanSpeakerNotesForBlueprint(notes?: string): string {
	if (!notes || !notes.trim()) return '';
	const lines = notes.split(/\r?\n/);
	const cleanedLines: string[] = [];

	for (const line of lines) {
		const trimmed = line.trim();
		// Skip the opening > [!note] header line if it only has the default title
		const headerMatch = trimmed.match(/^>\s*\[!(?:note|notes|speaker-note)\]\s*(.*)$/i);
		if (headerMatch) {
			const customTitle = (headerMatch[1] || '').trim();
			if (customTitle && !/^(?:speaker\s*notes?|ノート|発表者ノート|補足)/i.test(customTitle)) {
				cleanedLines.push(customTitle);
			}
			continue;
		}
		cleanedLines.push(line.replace(/^>\s?/, '').replace(/<span class="presenter-badge">(.*?)<\/span>/g, '[$1]'));
	}

	return cleanedLines.join('\n').trim();
}

/**
 * Estimates speaking duration in seconds and character count for speaker script text.
 * Assumes ~320 chars/min for CJK text and ~140 words/min (~700 chars/min) for Latin text.
 */
export function estimateScriptMetrics(notes?: string): { charCount: number; estimatedSeconds: number } {
	const cleaned = cleanSpeakerNotesForBlueprint(notes);
	if (!cleaned) {
		return { charCount: 0, estimatedSeconds: 0 };
	}

	const compact = cleaned.replace(/\s+/g, '');
	const charCount = compact.length;
	if (charCount === 0) {
		return { charCount: 0, estimatedSeconds: 0 };
	}

	const cjkMatches = compact.match(/[\u3000-\u9fff\uf900-\ufaff]/g);
	const cjkCount = cjkMatches ? cjkMatches.length : 0;
	const nonCjkText = cleaned.replace(/[\u3000-\u9fff\uf900-\ufaff]/g, ' ').trim();
	const wordCount = nonCjkText ? nonCjkText.split(/\s+/).filter(Boolean).length : 0;

	// ~5.5 CJK chars per second (~330 chars/min), ~2.3 English words per second (~140 wpm)
	const seconds = Math.max(5, Math.round((cjkCount / 5.5 + wordCount / 2.3) / 5) * 5);
	return { charCount, estimatedSeconds: seconds };
}

/**
 * Extracts a structured AI Slide Storyboard & Master Script Blueprint
 * designed to be pasted directly into AI slide generators (Gamma, Claude Artifacts, Genspark, ChatGPT, etc.).
 */
export function extractAiSlideBlueprint(presentation: PresentationData): string {
	const lines: string[] = [];
	const total = presentation.slides.length;
	const aspectRatio = presentation.frontmatter.aspectRatio || '16:9';

	lines.push('# 🎬 Presentation Storyboard & Master Script Blueprint');
	lines.push('');
	lines.push('> **Instructions for AI Slide Generator / LLM (Gamma, Claude, Genspark, etc.)**:');
	lines.push('> Below is a structured **Slide-by-Slide Storyboard & Speaker Script Blueprint** authored in Obsidian Presenter.');
	lines.push('> - **1 Slide = 1 Core Message**: Keep the exact slide count and sequence. Use each slide\'s `Action Title` as the headline conclusion.');
	lines.push('> - **Visual Archetype & Layout Intent**: Follow the specified `Archetype` and `Layout Intent` to structure columns, comparisons, flows, or KPIs.');
	lines.push('> - **Visual vs. Spoken Separation**: Keep on-slide text concise (`Visual Storyboard Body`). Use `Speaker Script & Context` for narrative transitions, background evidence, or speaker notes.');
	lines.push('');
	lines.push('## Deck Metadata');
	lines.push(`- **Title**: ${presentation.title}`);
	lines.push(`- **Total Slides**: ${total}`);
	lines.push(`- **Aspect Ratio**: ${aspectRatio}`);
	if (presentation.frontmatter.header) {
		lines.push(`- **Header**: ${presentation.frontmatter.header}`);
	}

	presentation.slides.forEach((slide, idx) => {
		const num = idx + 1;
		const { archetype, layoutIntent } = inferSlideLayoutBlueprint(slide);
		const bodyMd = cleanSlideMarkdownForBlueprint(slide.markdown);
		const scriptText = cleanSpeakerNotesForBlueprint(slide.notes);

		lines.push('');
		lines.push('---');
		lines.push('');
		lines.push(`### Slide ${num} / ${total} [${archetype}]`);
		lines.push(`- **Action Title**: ${slide.title}`);
		lines.push(`- **Layout Intent**: ${layoutIntent.trim()}`);

		if (bodyMd) {
			lines.push('- **Visual Storyboard Body**:');
			for (const bLine of bodyMd.split('\n')) {
				lines.push(`  ${bLine}`);
			}
		}

		if (scriptText) {
			const { estimatedSeconds } = estimateScriptMetrics(slide.notes);
			lines.push(`- **🎙 Speaker Script & Context (~${estimatedSeconds}s)**:`);
			for (const sLine of scriptText.split('\n')) {
				lines.push(`  ${sLine}`);
			}
		}
	});

	return lines.join('\n');
}

/**
 * Extracts an executive summary from a presentation for quick sharing
 * in Slack, Teams, email, or meeting notes.
 */
export function extractPresentationSummary(presentation: PresentationData): string {
	const lines: string[] = [];
	lines.push(`# ${presentation.title}`);
	lines.push('');
	lines.push('## 📋 Slide Outline');

	presentation.slides.forEach((slide, idx) => {
		const num = idx + 1;
		const isSection = slide.layout === 'section' || slide.type === 'section';
		const badge =
			slide.type === 'cover'
				? '【Cover】'
				: isSection
					? '【Section】'
					: slide.type === 'quote'
						? '【Quote】'
						: '';

		lines.push(`${num}. ${badge ? badge + ' ' : ''}${slide.title}`);
	});

	// Extract Key Takeaways & Callouts
	const highlights: string[] = [];

	presentation.slides.forEach((slide, idx) => {
		const slideLines = slide.markdown.split(/\r?\n/);
		const slideNum = idx + 1;

		for (const line of slideLines) {
			const trimmed = line.trim();
			// Match callouts like > [!important] or > [!tip] or > [!summary]
			const calloutMatch = trimmed.match(/^>\s*\[!(important|tip|summary|warning|check|info)\]\s*(.*)$/i);
			if (calloutMatch && calloutMatch[2]) {
				highlights.push(`- **p.${slideNum} ${slide.title}**: ${calloutMatch[2].trim()}`);
			}

			// Match badges like [重要] or <span class="presenter-badge">重要</span>
			const badgeMatch = trimmed.match(/^[-*]\s*(?:\[(.*?)]|<span class="presenter-badge">(.*?)<\/span>)\s*(.*)$/);
			if (badgeMatch) {
				const label = (badgeMatch[1] || badgeMatch[2] || '').trim();
				const text = (badgeMatch[3] || '').trim();
				if (label === '重要' || label === 'IMPORTANT' || label === 'POINT' || label === 'TASK' || label === '課題') {
					highlights.push(`- **p.${slideNum} [${label}]**: ${text}`);
				}
			}
		}
	});

	if (highlights.length > 0) {
		lines.push('');
		lines.push('## 💡 Key Highlights & Takeaways');
		lines.push(...highlights);
	}

	return lines.join('\n');
}

/**
 * Registers the summary and AI blueprint export commands.
 */
export function registerSummaryCommand(plugin: PresenterPlugin): void {
	plugin.addCommand({
		id: 'copy-ai-slide-blueprint',
		name: 'Copy AI slide prompt & storyboard blueprint',
		callback: async () => {
			const activeFile = plugin.app.workspace.getActiveFile();
			if (!activeFile) {
				new Notice('Please open a presentation note first.');
				return;
			}

			try {
				const content = await plugin.app.vault.read(activeFile);
				const settings = plugin.settings;
				const presentation = parsePresentation(content, {
					defaultColumnStyle: settings.defaultColumnStyle,
					enableBadges: settings.enableBadges,
					enableSmartLayouts: settings.enableSmartLayouts,
					inheritSlideHeadings: settings.inheritSlideHeadings,
					headingContinuationPrefix: settings.headingContinuationPrefix,
				});

				const blueprint = extractAiSlideBlueprint(presentation);
				await navigator.clipboard.writeText(blueprint);
				new Notice('AI slide blueprint & speaker script copied to clipboard!');
			} catch (err) {
				console.error('Failed to copy AI slide blueprint:', err);
				new Notice('Failed to copy AI slide blueprint.');
			}
		},
	});

	plugin.addCommand({
		id: 'copy-presentation-summary',
		name: 'Copy executive summary for sharing',
		callback: async () => {
			const activeFile = plugin.app.workspace.getActiveFile();
			if (!activeFile) {
				new Notice('Please open a presentation note first.');
				return;
			}

			try {
				const content = await plugin.app.vault.read(activeFile);
				const settings = plugin.settings;
				const presentation = parsePresentation(content, {
					defaultColumnStyle: settings.defaultColumnStyle,
					enableBadges: settings.enableBadges,
					enableSmartLayouts: settings.enableSmartLayouts,
					inheritSlideHeadings: settings.inheritSlideHeadings,
					headingContinuationPrefix: settings.headingContinuationPrefix,
				});

				const summary = extractPresentationSummary(presentation);
				await navigator.clipboard.writeText(summary);
				new Notice('Presentation summary copied to clipboard!');
			} catch (err) {
				console.error('Failed to copy presentation summary:', err);
				new Notice('Failed to copy presentation summary.');
			}
		},
	});
}
