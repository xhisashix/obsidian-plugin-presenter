import {
	type App,
	Component,
	MarkdownRenderer,
	TFile,
} from 'obsidian';
import PptxGenJS from 'pptxgenjs';
import type { PresentationData, PresenterSettings } from '../types';
import { waitForEmbeddedDiagrams } from '../ui/slideRenderer';
import { inlineLocalImages, resolveLogoDataUrl } from './imageInliner';
import {
	extractSlideBlocksFromDom,
	formatSpeakerNotesForPptx,
	rasterizeSvgElementsToImages,
} from './pptxDomParser';
import { renderPptxSlide } from './pptxLayoutRenderer';
import { buildPptxTheme } from './pptxTheme';
import type { ExtractedSlideContent, PptxTheme } from './pptxTypes';

/**
 * Generates a `.pptx` binary `ArrayBuffer` from pre-extracted slide structures and theme.
 */
export async function buildPptxFromExtractedSlides(
	presentation: PresentationData,
	extractedSlides: ExtractedSlideContent[],
	theme: PptxTheme
): Promise<ArrayBuffer> {
	const pptx = new PptxGenJS();

	pptx.title = presentation.title || 'Presentation';
	pptx.subject = 'Generated by Obsidian Presenter';
	pptx.author = 'Obsidian Presenter';
	pptx.layout = theme.aspectRatio === '4:3' ? 'LAYOUT_4x3' : 'LAYOUT_WIDE';

	const totalSlides = presentation.slides.length;

	for (let i = 0; i < presentation.slides.length; i++) {
		const slideData = presentation.slides[i]!;
		const extracted = extractedSlides[i];
		const blocks = extracted ? extracted.blocks : [];
		const notesText = extracted?.notesText ?? formatSpeakerNotesForPptx(slideData.notes);

		const pptxSlide = pptx.addSlide();
		renderPptxSlide(pptx, pptxSlide, slideData, blocks, theme, totalSlides);

		if (notesText) {
			pptxSlide.addNotes(notesText);
		}
	}

	const output = await pptx.write({
		outputType: 'arraybuffer',
		compression: true,
	});

	if (output instanceof ArrayBuffer) {
		return output;
	}
	if (ArrayBuffer.isView(output)) {
		const copy = new Uint8Array(output.byteLength);
		copy.set(new Uint8Array(output.buffer, output.byteOffset, output.byteLength));
		return copy.buffer;
	}
	throw new Error('Unexpected output type from PptxGenJS write()');
}

/**
 * Renders a presentation's slides through Obsidian's MarkdownRenderer, extracts native
 * slide blocks and diagrams, and builds a PowerPoint (.pptx) binary ArrayBuffer.
 */
export async function exportPresentationToPptx(
	app: App,
	file: TFile,
	presentation: PresentationData,
	settings: PresenterSettings
): Promise<ArrayBuffer> {
	const component = new Component();
	component.load();

	const config = presentation.frontmatter;
	const imageCache = new Map<string, string>();

	let logoDataUrl: string | null = null;
	const logoInput = config.logo !== undefined ? config.logo : settings.defaultLogo;
	if (logoInput && logoInput.trim()) {
		logoDataUrl = await resolveLogoDataUrl(app, logoInput, file.path, imageCache);
	}

	const theme = buildPptxTheme(config, settings, logoDataUrl);
	const extractedSlides: ExtractedSlideContent[] = [];

	const doc = typeof activeDocument !== 'undefined' ? activeDocument : document;
	const tempContainer = doc.body.createDiv({ cls: 'presenter-hidden-export' });

	try {
		for (const slide of presentation.slides) {
			const slideDiv = tempContainer.createDiv({
				cls: 'presenter-slide-body markdown-rendered',
			});

			await MarkdownRenderer.render(app, slide.markdown, slideDiv, file.path, component);
			await waitForEmbeddedDiagrams(slideDiv);
			await rasterizeSvgElementsToImages(slideDiv, theme.baseColor, theme.mainColor);
			await inlineLocalImages(app, slideDiv, file.path, imageCache);

			const blocks = extractSlideBlocksFromDom(slideDiv);
			const notesText = formatSpeakerNotesForPptx(slide.notes);

			extractedSlides.push({
				index: slide.index,
				layout: slide.layout || slide.type,
				title: slide.title,
				blocks,
				notesText,
			});

			tempContainer.empty();
		}
	} finally {
		component.unload();
		tempContainer.remove();
	}

	return await buildPptxFromExtractedSlides(presentation, extractedSlides, theme);
}

/**
 * Saves the generated `.pptx` binary to the same vault folder as the source note
 * and triggers a browser file download.
 */
export async function saveAndDownloadPptx(
	app: App,
	file: TFile,
	pptxBuffer: ArrayBuffer
): Promise<string> {
	const baseName = file.basename;
	const parentPath = file.parent ? file.parent.path : '';
	const exportFileName = `${baseName}-presentation.pptx`;
	const exportPath =
		parentPath && parentPath !== '/'
			? `${parentPath}/${exportFileName}`
			: exportFileName;

	const existingFile = app.vault.getAbstractFileByPath(exportPath);
	if (existingFile instanceof TFile) {
		await app.vault.modifyBinary(existingFile, pptxBuffer);
	} else {
		await app.vault.createBinary(exportPath, pptxBuffer);
	}

	if (typeof activeDocument !== 'undefined' && typeof URL !== 'undefined') {
		const blob = new Blob([pptxBuffer], {
			type: 'application/vnd.openxmlformats-officedocument.presentationml.presentation',
		});
		const url = URL.createObjectURL(blob);
		const link = activeDocument.body.createEl('a', {
			href: url,
			attr: { download: exportFileName },
		});
		link.click();
		link.remove();
		URL.revokeObjectURL(url);
	}

	return exportPath;
}
