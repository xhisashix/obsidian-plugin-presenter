import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import path from 'node:path';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

/**
 * Resolves JSZip to its unbundled CommonJS source (`lib/index.js`) and shims
 * its legacy IE6–8 polyfills (`lie` and `setimmediate`) and Node stream adapter
 * so that `document.createElement('script')` and `new Function()` from
 * `jszip/dist/jszip.min.js` are never bundled into `main.js`.
 */
const jszipBrowserCleanPlugin = {
	name: 'jszip-browser-clean',
	setup(build) {
		build.onResolve({ filter: /^jszip$/ }, () => ({
			path: path.resolve('node_modules/jszip/lib/index.js'),
		}));

		build.onResolve(
			{ filter: /^(lie|setimmediate|readable-stream)$/ },
			(args) => ({
				path: args.path,
				namespace: 'jszip-shim',
			})
		);

		build.onLoad({ filter: /^lie$/, namespace: 'jszip-shim' }, () => ({
			contents: 'module.exports = Promise;',
			loader: 'js',
		}));

		build.onLoad(
			{ filter: /^setimmediate$/, namespace: 'jszip-shim' },
			() => ({
				contents: `
					if (typeof globalThis.setImmediate !== 'function') {
						globalThis.setImmediate = (fn, ...args) => setTimeout(fn, 0, ...args);
						globalThis.clearImmediate = (id) => clearTimeout(id);
					}
				`,
				loader: 'js',
			})
		);

		build.onLoad(
			{ filter: /^readable-stream$/, namespace: 'jszip-shim' },
			() => ({
				contents: 'module.exports = { Readable: null };',
				loader: 'js',
			})
		);
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	plugins: [jszipBrowserCleanPlugin],
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
